function translateTemplate(value, variables = {}) {
    return Object.entries(variables).reduce(
        (result, [key, replacement]) => result.replace(`{${key}}`, replacement),
        value
    );
}

function applyLanguage(language) {
    currentLanguage = language;
    document.documentElement.lang = language;
    document.documentElement.dataset.language = language;

    document.querySelectorAll("[data-copy]").forEach((element) => {
        const key = element.dataset.copy;
        const value = translations[language][key];
        if (!value) return;
        if (key.startsWith("bookInstruction")) {
            element.innerHTML = value;
        } else {
            element.textContent = value;
        }
    });

    languageCurrent.textContent = language.toUpperCase();
    languageOther.textContent = language === "en" ? "IT" : "EN";
    languageToggle.setAttribute(
        "aria-label",
        language === "en" ? "Passa alla lingua italiana" : "Switch to English"
    );
    placeSheetClose.setAttribute("aria-label", translations[language].closePlace);
    updateJourneyCount();
    renderPlaceList();

    if (selectedPlaceIndex !== null) {
        renderPlaceSheet(places[selectedPlaceIndex]);
    }

    try {
        localStorage.setItem("portfolio-language", language);
    } catch {
        // The language choice still works when storage is unavailable.
    }
}

function localised(place, key) {
    if (currentLanguage === "it") {
        return place[`${key}It`] || place[key];
    }
    return place[key];
}

function updateJourneyCount() {
    const countries = new Set(places.map((place) => place.country)).size;
    journeyCount.textContent = translateTemplate(translations[currentLanguage].journeyCount, {
        places: places.length,
        countries
    });
}

