let timelineFrameRequested = false;

function updateTimelineProgress() {
    timelineFrameRequested = false;
    if (!careerTimeline) return;

    const rect = careerTimeline.getBoundingClientRect();
    const startLine = window.innerHeight * 0.68;
    const usableDistance = Math.max(rect.height, 1);
    const progress = Math.min(1, Math.max(0, (startLine - rect.top) / usableDistance));
    careerTimeline.style.setProperty("--timeline-progress", `${progress * 100}%`);
}

function requestTimelineProgressUpdate() {
    if (timelineFrameRequested) return;
    timelineFrameRequested = true;
    window.requestAnimationFrame(updateTimelineProgress);
}

window.addEventListener("scroll", requestTimelineProgressUpdate, { passive: true });
window.addEventListener("resize", requestTimelineProgressUpdate, { passive: true });
updateTimelineProgress();

function imagePath(filename, thumbnail = false) {
    if (thumbnail) {
        const stem = filename.replace(/\.[^.]+$/, "");
        return `assets/images/map/thumbs/${stem}.webp`;
    }
    return `assets/images/map/${filename}`;
}

function placeTypeLabel(type) {
    const key = type === "research" ? "researchBadge" : type === "study" ? "studyBadge" : "travelBadge";
    return translations[currentLanguage][key];
}

function renderPlaceSheet(place) {
    const images = place.images
        .map((filename, index) => {
            const label = translateTemplate(translations[currentLanguage].photoLabel, {
                index: index + 1,
                total: place.images.length
            });
            return `
                <figure>
                    <a href="${imagePath(filename)}" target="_blank" rel="noopener" aria-label="${label}">
                        <img src="${imagePath(filename, true)}" alt="${localised(place, "name")} — ${label}" loading="lazy">
                    </a>
                    ${place.images.length > 1 ? `<figcaption>${label}</figcaption>` : ""}
                </figure>
            `;
        })
        .join("");

    placeSheetContent.innerHTML = `
        <div class="place-gallery">${images}</div>
        <div class="place-meta">
            <span>${localised(place, "country")}</span>
            <span>${localised(place, "period")}</span>
        </div>
        <h3>${localised(place, "name")}</h3>
        <p>${localised(place, "description")}</p>
        <span class="place-badge">${placeTypeLabel(place.type)}</span>
    `;
}

function selectPlace(index, moveMap = true) {
    const place = places[index];
    selectedPlaceIndex = index;

    if (selectedMarker?.getElement()) {
        selectedMarker.getElement().querySelector(".map-marker")?.classList.remove("selected");
    }

    selectedMarker = mapMarkers[index];
    if (selectedMarker?.getElement()) {
        selectedMarker.getElement().querySelector(".map-marker")?.classList.add("selected");
    }

    renderPlaceSheet(place);
    placeSheet.classList.add("open");
    placeSheet.setAttribute("aria-hidden", "false");
    placeSheetClose.classList.add("visible");

    if (moveMap && mapInstance) {
        const targetZoom = window.matchMedia("(max-width: 620px)").matches ? 6 : 7;
        mapInstance.flyTo(place.coords, Math.max(mapInstance.getZoom(), targetZoom), {
            duration: 0.75
        });
    }
}

function closePlaceSheet() {
    placeSheet.classList.remove("open");
    placeSheet.setAttribute("aria-hidden", "true");
    placeSheetClose.classList.remove("visible");

    if (selectedMarker?.getElement()) {
        selectedMarker.getElement().querySelector(".map-marker")?.classList.remove("selected");
    }
    selectedMarker = null;
    selectedPlaceIndex = null;
}

placeSheetClose.addEventListener("click", closePlaceSheet);

function renderPlaceList() {
    placeList.innerHTML = places
        .map(
            (place, index) => `
                <button class="place-list-card" type="button" data-place-index="${index}">
                    <img src="${imagePath(place.images[0], true)}" alt="" loading="lazy">
                    <div>
                        <span>${localised(place, "country")} · ${localised(place, "period")}</span>
                        <h3>${localised(place, "name")}</h3>
                        <p>${localised(place, "description")}</p>
                    </div>
                </button>
            `
        )
        .join("");

    placeList.querySelectorAll(".place-list-card").forEach((card) => {
        card.addEventListener("click", () => {
            switchJourneyView("map");
            selectPlace(Number(card.dataset.placeIndex));
        });
    });
}

function switchJourneyView(view) {
    const showMap = view === "map";
    mapViewButton.classList.toggle("active", showMap);
    mapViewButton.setAttribute("aria-selected", String(showMap));
    listViewButton.classList.toggle("active", !showMap);
    listViewButton.setAttribute("aria-selected", String(!showMap));
    mapView.hidden = !showMap;
    placeList.hidden = showMap;

    if (showMap && mapInstance) {
        window.setTimeout(() => mapInstance.invalidateSize(), 50);
    }
}

mapViewButton.addEventListener("click", () => switchJourneyView("map"));
listViewButton.addEventListener("click", () => switchJourneyView("list"));

function initialiseMap() {
    if (typeof L === "undefined") {
        document.getElementById("map").innerHTML = `<p class="noscript-note">${translations[currentLanguage].mapUnavailable}</p>`;
        switchJourneyView("list");
        return;
    }

    mapInstance = L.map("map", {
        scrollWheelZoom: false,
        dragging: true,
        touchZoom: true,
        tap: true,
        zoomControl: true,
        attributionControl: true
    });

    L.tileLayer("https://{s}.basemaps.cartocdn.com/light_all/{z}/{x}/{y}{r}.png", {
        attribution: "&copy; OpenStreetMap &copy; CARTO",
        subdomains: "abcd",
        maxZoom: 19
    }).addTo(mapInstance);

    places.forEach((place, index) => {
        const initials = place.name
            .split(/\s+/)
            .map((word) => word[0])
            .join("")
            .slice(0, 2)
            .toUpperCase();
        const icon = L.divIcon({
            className: "map-marker-wrap",
            html: `<div class="map-marker"><span>${initials}</span></div>`,
            iconSize: [44, 44],
            iconAnchor: [22, 40]
        });

        const marker = L.marker(place.coords, {
            icon,
            keyboard: true,
            title: place.name,
            alt: place.name
        }).addTo(mapInstance);

        marker.on("click", () => selectPlace(index, false));
        marker.on("keypress", (event) => {
            if (event.originalEvent.key === "Enter" || event.originalEvent.key === " ") {
                selectPlace(index, false);
            }
        });
        mapMarkers.push(marker);
    });

    const bounds = L.latLngBounds(places.map((place) => place.coords));
    mapInstance.fitBounds(bounds.pad(0.08), {
        maxZoom: 4
    });

    mapInstance.on("click", (event) => {
        if (event.originalEvent.target.closest?.(".map-marker")) return;
        closePlaceSheet();
    });
}

